create table if not exists public.products (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null,
  price integer not null,
  compare_at_price integer,
  tag text,
  image text not null,
  image_alt text not null,
  tint text not null default '#e9e5dc',
  description text not null,
  details text[] not null default '{}'::text[],
  sizes text[] not null default '{}'::text[],
  rating numeric(2,1) not null default 0,
  review_count integer not null default 0,
  featured boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_slug_format check (
    slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' and slug !~ '^[0-9]+$'
  ),
  constraint products_category_check check (
    category in ('T-Shirts', 'Outerwear', 'Bottoms', 'Knitwear', 'Shirts', 'Accessories')
  ),
  constraint products_tag_check check (
    tag is null or tag in ('BESTSELLER', 'NEW ARRIVAL', 'POPULAR', 'LIMITED')
  ),
  constraint products_price_check check (price between 1000 and 100000000),
  constraint products_compare_price_check check (
    compare_at_price is null
    or (compare_at_price > price and compare_at_price <= 100000000)
  ),
  constraint products_sizes_check check (
    cardinality(sizes) > 0
    and sizes <@ array['S', 'M', 'L', 'XL', 'All Size']::text[]
  ),
  constraint products_rating_check check (rating >= 0 and rating <= 5),
  constraint products_review_count_check check (review_count >= 0),
  constraint products_tint_check check (tint ~ '^#[0-9a-fA-F]{6}$')
);

create index if not exists products_active_created_at_idx
  on public.products (is_active, created_at desc);
create index if not exists products_category_idx
  on public.products (category);
create index if not exists products_featured_idx
  on public.products (featured)
  where featured = true;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at
before update on public.products
for each row execute function public.touch_updated_at();

alter table public.products enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products
for select
to anon, authenticated
using (is_active = true);

