-- ---------------------------------------------------------------------------
-- Discount codes
-- ---------------------------------------------------------------------------

create table if not exists public.discounts (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  description text,
  type text not null,
  value integer not null,
  min_subtotal integer not null default 0,
  max_discount integer,
  starts_on date,
  ends_on date,
  usage_limit integer,
  used_count integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint discounts_code_format check (code ~ '^[A-Z0-9][A-Z0-9-]{2,31}$'),
  constraint discounts_type_check check (type in ('percentage', 'fixed')),
  constraint discounts_percentage_value check (
    type <> 'percentage' or value between 1 and 100
  ),
  constraint discounts_fixed_value check (
    type <> 'fixed' or value between 1000 and 100000000
  ),
  constraint discounts_min_subtotal_check check (min_subtotal >= 0),
  constraint discounts_max_discount_check check (
    max_discount is null or max_discount > 0
  ),
  constraint discounts_dates_check check (
    starts_on is null or ends_on is null or starts_on <= ends_on
  ),
  constraint discounts_usage_limit_check check (
    usage_limit is null or usage_limit > 0
  ),
  constraint discounts_used_count_check check (
    used_count >= 0 and (usage_limit is null or used_count <= usage_limit)
  )
);

create index if not exists discounts_active_idx
  on public.discounts (is_active, starts_on, ends_on);

drop trigger if exists discounts_touch_updated_at on public.discounts;
create trigger discounts_touch_updated_at
before update on public.discounts
for each row execute function public.touch_updated_at();

alter table public.discounts enable row level security;
